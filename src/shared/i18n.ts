const TABLES: Record<Language, Messages> = { en, pt };
let current: Language = "en";

export function language(): Language {
  return current;
}

/** Every text after this is in `lang`; the page says so to assistive tech. */
export function setLanguage(lang: Language): void {
  current = lang;
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
}

type Args<K extends Key> = Messages[K] extends (...args: infer A) => string ? A : [];

/** The text of `key` in the current language. */
export function t<K extends Key>(key: K, ...args: Args<K>): string {
  const text: unknown = TABLES[current][key];
  return typeof text === "function" ? (text as (...values: unknown[]) => string)(...args) : (text as string);
}

